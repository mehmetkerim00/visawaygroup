#!/usr/bin/env node
/*
 * build-vercel.js — сборка сайта на стороне хостинга.
 *
 * ЗАЧЕМ ОНА ЕСТЬ. Раньше страницы собирались на вашем компьютере и
 * ложились в репозиторий готовыми. Пока требования правились в файле,
 * этого хватало. Теперь их правит специалист в панели, и данные лежат
 * в базе — значит, собирать надо там, где база доступна в момент
 * выкладки. Иначе кнопка «Опубликовать» не могла бы ничего изменить.
 *
 * Порядок такой:
 *   1. выгрузить требования из базы в data/requirements.json;
 *   2. собрать страницы и разложить по ним шапку, подвал, разметку;
 *   3. прогнать preflight;
 *   4. отметить в базе, что собранное уехало на сайт;
 *   5. убрать из выкладки сам файл требований.
 *
 * Последний шаг — про открытый файл. data/requirements.json лежал бы в
 * корне сайта и читался бы по прямому адресу целиком, вместе с заметками
 * специалиста, которых на страницах нет. Собранным страницам он после
 * сборки не нужен, браузер его не запрашивает ни разу, поэтому на
 * хостинге он удаляется. В репозитории и на вашем компьютере остаётся.
 *
 * Если preflight не пропускает — выходим с ошибкой. Vercel тогда не
 * заменяет сайт: прежняя версия остаётся жить. Это и есть страховка,
 * про которую шла речь: неудачная сборка не ломает работающий сайт.
 *
 * Страницы требований собираются для всех записей: статус на видимость
 * больше не влияет.
 */

"use strict";

const { spawnSync } = require("child_process");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");

/* На Vercel переменные приходят от самого хостинга. Локально они лежат
   в .env.local — без этого проверить сборку у себя было бы нельзя:
   она молча пропускала бы выгрузку из базы. */
try {
  if (require("fs").existsSync(path.join(ROOT, ".env.local"))) {
    process.loadEnvFile(path.join(ROOT, ".env.local"));
  }
} catch (e) { /* старый Node — переменные задаются вручную */ }

function step(name, file, args) {
  console.log("");
  console.log("── " + name + " " + "─".repeat(Math.max(0, 60 - name.length)));
  const r = spawnSync(process.execPath, [path.join(ROOT, "scripts", file)].concat(args || []), {
    stdio: "inherit",
    cwd: ROOT
  });
  if (r.status !== 0) {
    console.error("");
    console.error("ОСТАНОВЛЕНО НА ШАГЕ: " + name);
    console.error("Сайт не заменён — продолжает работать прежняя версия.");
    process.exit(r.status || 1);
  }
}

/* Отмечаем в базе, что собранное уехало на сайт.
 *
 * Сайт пересобирается не только кнопкой в панели, но и от правки в
 * репозитории. Если отметку ставила бы только кнопка, панель после такой
 * выкладки вечно показывала бы «правок ещё нет на сайте», хотя они там.
 *
 * Шаг идёт после preflight: отмечаем только то, что и правда выкладываем.
 * Падение здесь выкладку не роняет — страницы уже собраны, и потерять
 * отметку дешевле, чем потерять сборку. */
function отметитьОпубликованное() {
  if (!process.env.KV_REST_API_URL) return;
  const r = spawnSync(process.execPath, [path.join(ROOT, "scripts", "admin-init.js"), "stamp"],
                      { stdio: "inherit", cwd: ROOT });
  if (r.status !== 0) {
    console.error("");
    console.error("Отметка о публикации не проставилась — сайт это не ломает.");
    console.error("Панель может показывать неопубликованные правки там, где они уже на сайте.");
  }
}

/* Удаляем файл требований из того, что уедет на сайт.
 *
 * Только на хостинге: там сборка идёт в свежей копии репозитория, и
 * удалять там нечего — файл только что выгружен из базы. На вашем
 * компьютере это те самые рабочие данные, их трогать нельзя.
 *
 * data/countries.json остаётся: его подключает панель через require,
 * и он попадает в её код при сборке. Ничего секретного в нём нет —
 * это названия стран. */
function скрытьФайлТребований() {
  if (process.env.VERCEL !== "1") return;

  const fs = require("fs");
  const файл = path.join(ROOT, "data", "requirements.json");
  if (!fs.existsSync(файл)) return;

  const размер = fs.statSync(файл).size;
  fs.unlinkSync(файл);
  console.log("");
  console.log("Файл требований убран из выкладки (" + Math.round(размер / 1024) + " КБ).");
  console.log("Тексты записей не будут доступны по адресу /data/requirements.json.");
}

function main() {
  console.log("СБОРКА САЙТА НА ХОСТИНГЕ");

  /* Без ключей хранилища выгружать нечего. Это не повод падать: если
     кто-то соберёт проект без панели, сайт должен собраться из файла,
     который лежит в репозитории. */
  if (!process.env.KV_REST_API_URL) {
    console.log("");
    console.log("  Хранилище панели не подключено — берём требования из файла.");
  } else {
    step("Выгрузка требований из базы", "admin-init.js", ["export"]);
  }

  step("Сборка страниц", "build.js");
  step("Проверка перед публикацией", "preflight.js");

  отметитьОпубликованное();
  скрытьФайлТребований();

  console.log("");
  console.log("Готово. Сайт собран.");
}

main();
